def mk(rows, hidden=False):
    out = []
    for author, source, date, stars, text, photos in rows:
        item = {
            "author": author,
            "source": source,
            "date": date,
            "stars": stars,
            "text": text,
            "photos": photos,
        }
        if hidden:
            item["hidden"] = True
        out.append(item)
    return out


